export function parseCode(code) {
  const m = CODE_RE.exec(code || '');
  if (!m || m[5] === m[6]) return null;
  return { core: m[1] + m[2] + m[3] + m[4], att: m[1] + m[2], pace: m[3] + m[4], ll: m[6] ? [m[5], m[6]] : [m[5]] };
}

